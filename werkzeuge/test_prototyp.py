import asyncio, sys, os
from playwright.async_api import async_playwright
FILE, OUT = sys.argv[1], sys.argv[2]
WEB = len(sys.argv) > 3
os.makedirs(OUT, exist_ok=True)
async def click(page, text, exact=False, nth=0, role="button"):
    await page.get_by_role(role, name=text, exact=exact).nth(nth).click()
    await page.wait_for_timeout(150)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        errors = []
        def watch(pg):
            pg.on("pageerror", lambda e: errors.append(str(e)))
            pg.on("console", lambda m: errors.append(m.text) if m.type == "error" else None)
        ctx = await b.new_context(viewport={"width": 390, "height": 1500}, is_mobile=True, has_touch=True)
        pg = await ctx.new_page(); watch(pg)
        await pg.goto("file://" + FILE + "?app"); await pg.wait_for_timeout(400)
        await click(pg, "Ohne Profil starten")
        await pg.screenshot(path=f"{OUT}/a1-home.png")
        await click(pg, "Touren", exact=True)
        await click(pg, "Tour empfangen")
        await pg.screenshot(path=f"{OUT}/a0-scan.png")
        await click(pg, "Code scannen (Vorschau)")
        await pg.screenshot(path=f"{OUT}/a0b-received.png")
        await click(pg, "Entdecken", exact=True)
        await click(pg, "Street Art am Bahnbogen")
        await pg.screenshot(path=f"{OUT}/a2-near-preview.png")
        await click(pg, "Für später speichern")
        await click(pg, "Zurück")
        await click(pg, "Touren", exact=True)
        await pg.screenshot(path=f"{OUT}/a3-touren.png")
        await click(pg, "Sagenhafte Altstadt")
        await pg.screenshot(path=f"{OUT}/a4-planned-preview.png")
        await click(pg, "Zurück")
        await click(pg, "Zeitreise Altstadt")
        await pg.screenshot(path=f"{OUT}/a5-diary.png")
        await pg.goto("file://" + FILE + "?app"); await pg.wait_for_timeout(400)
        await click(pg, "Ohne Profil starten")
        await click(pg, "Neue Tour planen")
        await click(pg, "Gruppe", exact=True)
        await click(pg, "Natur", exact=True)
        pass
        await pg.screenshot(path=f"{OUT}/a6-plan-group.png")
        await click(pg, "Gruppen-Tour erstellen")
        await pg.screenshot(path=f"{OUT}/a7-preview-long.png")
        await click(pg, "Für alle starten")
        await pg.wait_for_timeout(300)
        await pg.screenshot(path=f"{OUT}/a8-live.png")
        await ctx.close()
        if WEB:
            ctx = await b.new_context(viewport={"width": 1440, "height": 900})
            pg = await ctx.new_page(); watch(pg)
            await pg.goto("file://" + FILE); await pg.wait_for_timeout(400)
            await pg.screenshot(path=f"{OUT}/w1-guest.png", full_page=False)
            await pg.mouse.wheel(0, 900); await pg.wait_for_timeout(200)
            await pg.screenshot(path=f"{OUT}/w1b-guest-scrolled.png")
            await click(pg, "Anmelden", exact=True)
            await pg.screenshot(path=f"{OUT}/w2-home.png")
            await click(pg, "Hamburg", exact=True)
            await click(pg, "Tour planen", exact=True)
            await pg.screenshot(path=f"{OUT}/w3-plan.png")
            await click(pg, "Gruppe", exact=True)
            pass
            await pg.screenshot(path=f"{OUT}/w4-plan-group.png")
            await click(pg, "Meine Touren", exact=True)
            await pg.screenshot(path=f"{OUT}/w5-touren.png")
            await click(pg, "Konto und Abo", exact=True)
            await click(pg, "Abmelden", exact=True)
            await pg.screenshot(path=f"{OUT}/w6-logout.png")
            await ctx.close()
            ctx = await b.new_context(viewport={"width": 1280, "height": 720})
            pg = await ctx.new_page(); watch(pg)
            await pg.goto("file://" + FILE); await pg.wait_for_timeout(400)
            await click(pg, "Kostenlos starten", nth=0)
            await pg.screenshot(path=f"{OUT}/w7-home-1280.png")
            await ctx.close()
        await b.close()
        print("errors:", errors)
asyncio.run(main())
